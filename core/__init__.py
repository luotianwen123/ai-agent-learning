"""core —— mini-pi 的内核层

═══════════════════════════════════════════════════════════════
一、模块划分与调用方向
═══════════════════════════════════════════════════════════════

主链路（一次任务的完整路径）：

    内核.py ──→ loop.py ──→ core/llm.py ──→ DeepSeek API
                  │
                  ├──→ core/tools.py ──→ 文件系统 / 子进程
                  └──←── 结果字符串

不参与运行：

    check_llm.py       初始验证存档，禁止改造
    core/__init__.py   本文件，包标记

═══════════════════════════════════════════════════════════════
二、模块间传递的数据只有三类
═══════════════════════════════════════════════════════════════

    数据                     传递路径                 类型
    ─────────────────────────────────────────────────────────────
    messages 列表            内核 → loop → llm       字典列表，只增不减
    name + arguments_json    loop → tools            字符串
    工具返回值               tools → loop            字符串

═══════════════════════════════════════════════════════════════
三、各模块职责
═══════════════════════════════════════════════════════════════

    内核.py            入口。解析参数、驱动循环、输出进度
    loop.py            驱动。判定是否需要调用工具，串联模型与工具
    core/llm.py        模型调用层。全项目唯一的模型出入口
    core/tools.py      工具层。唯一会改动磁盘或启动子进程的模块
    core/__init__.py   包标记，使 from core.xxx import 成立
    check_llm.py       初始验证存档，不参与运行时

═══════════════════════════════════════════════════════════════
四、一次任务的数据流向
═══════════════════════════════════════════════════════════════

    ① 入口接收任务描述
    ② 构造 messages = [{"role": "user", "content": "..."}]
    ③ loop 以 messages + TOOLS 调用 core/llm.py 的 ask()
    ④ core/llm.py 发起 HTTP 请求，取回一条 message
    ⑤ message 若含 tool_calls
       → loop 将 name + arguments_json 交给 core/tools.py
    ⑥ core/tools.py 执行文件读写或命令，返回字符串
    ⑦ loop 将其作为 {"role": "tool", "content": ...} 回填 messages
    ⑧ 再次执行 ③④ —— 此时模型已持有真实结果，可给出最终回答
    ⑨ 结果返回 loop，输出到终端

    ③ 至 ⑧ 构成 Agent 循环。当前仅执行一次往返；
    将其包入 while 直至模型不再发起工具调用，即为多轮 Agent 的完整机制。

═══════════════════════════════════════════════════════════════
五、分层结构
═══════════════════════════════════════════════════════════════

    内核层  core/    调模型 · 执行工具 · 驱动循环
    评测层  eval/    固定任务集 · 回归测试 · 轨迹落盘
    自进化层 evo/    打分 · 闸门判定 · 可回滚

═══════════════════════════════════════════════════════════════
六、本文件不放置逻辑
═══════════════════════════════════════════════════════════════

__init__.py 中写逻辑会导致代码被藏在不会被主动打开的文件里。
此处仅将 core 目录标记为 Python 包。
"""
